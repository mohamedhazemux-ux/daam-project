// Simple auto-translator for remaining phrases
function autoTranslate(text) {
  if (dictionary[text]) return dictionary[text];
  if (phraseMap[text]) return phraseMap[text];

  let res = text;
  // Common prefixes
  if (res.startsWith('تم ') && res.endsWith(' بنجاح')) {
    const act = res.replace(/^تم\s+/, '').replace(/\s+بنجاح$/, '');
    return (phraseMap[act] || dictionary[act] || act) + ' completed successfully';
  }
  if (res.startsWith('تفاصيل ')) {
    const act = res.replace(/^تفاصيل\s+/, '');
    return (phraseMap[act] || dictionary[act] || act) + ' Details';
  }
  if (res.startsWith('إنشاء ')) {
    const act = res.replace(/^إنشاء\s+/, '');
    return 'Create ' + (phraseMap[act] || dictionary[act] || act);
  }
  if (res.startsWith('تعديل ')) {
    const act = res.replace(/^تعديل\s+/, '');
    return 'Edit ' + (phraseMap[act] || dictionary[act] || act);
  }
  if (res.startsWith('حذف ')) {
    const act = res.replace(/^حذف\s+/, '');
    return 'Delete ' + (phraseMap[act] || dictionary[act] || act);
  }
  if (res.startsWith('عرض ')) {
    const act = res.replace(/^عرض\s+/, '');
    return 'View ' + (phraseMap[act] || dictionary[act] || act);
  }
  if (res.startsWith('طلب ')) {
    const act = res.replace(/^طلب\s+/, '');
    return (phraseMap[act] || dictionary[act] || act) + ' Request';
  }
  if (res.endsWith(' مطلوب') || res.endsWith(' مطلوبة')) {
    const act = res.replace(/\s+مطلوب(ة)?$/, '');
    return (phraseMap[act] || dictionary[act] || act) + ' is required';
  }
  if (res.startsWith('بحث في ')) {
    const act = res.replace(/^بحث في\s+/, '').replace(/\.\.\.$/, '');
    return 'Search ' + (phraseMap[act] || dictionary[act] || act) + '...';
  }

  // Word by word replacement if still Arabic
  const words = res.split(' ');
  const translatedWords = words.map(w => dictionary[w] || phraseMap[w] || w);
  return translatedWords.join(' ');
}

