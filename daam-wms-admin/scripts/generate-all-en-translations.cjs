// Auto word replacer for any complex combined string
function fullTranslate(text) {
  if (exactMap[text]) return exactMap[text];

  let str = text;
  // Replace known subphrases
  Object.keys(exactMap).sort((a, b) => b.length - a.length).forEach(k => {
    if (str.includes(k)) {
      str = str.split(k).join(exactMap[k]);
    }
  });

  return str;
}

