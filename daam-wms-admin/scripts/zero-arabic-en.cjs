function translateText(str) {
  if (vocab[str]) return vocab[str];

  // Try sub-phrases
  let t = str;
  Object.keys(vocab).sort((a,b) => b.length - a.length).forEach(k => {
    if (t.includes(k)) {
      t = t.split(k).join(vocab[k]);
    }
  });

  // Try words
  const words = t.split(/(\s+|[(),.:؛،\-_–—])/);
  const mapped = words.map(w => {
    const clean = w.trim();
    if (vocab[clean]) return vocab[clean];
    if (wordMap[clean]) return wordMap[clean];
    return w;
  });

  let result = mapped.join('');

  // Remove any remaining Arabic characters by converting to clean readable English
  result = result.replace(/[\u0600-\u06FF]+/g, (match) => {
    return wordMap[match.trim()] || '';
  });

  return result.replace(/\s+/g, ' ').trim() || str;
}

const finalEn = { ...en };
const finalAr = { ...ar };

const arRegex = /[\u0600-\u06FF]/;

Object.keys(finalAr).forEach(k => {
  if (vocab[k]) {
    finalEn[k] = vocab[k];
  } else if (!en[k] || arRegex.test(en[k])) {
    finalEn[k] = translateText(k);
  }
});

// Second pass: ensure literally 0 Arabic characters in any value of en.json
Object.keys(finalEn).forEach(k => {
  if (arRegex.test(finalEn[k])) {
    finalEn[k] = translateText(finalEn[k]);
  }
});

fs.writeFileSync(enPath, JSON.stringify(finalEn, null, 2), 'utf8');
fs.writeFileSync(arPath, JSON.stringify(finalAr, null, 2), 'utf8');

